export function getTemplateById(id: string): MemeTemplate | undefined {
  return TEMPLATES.find((t) => t.id === id);
}

export function searchTemplates(query: string, category?: string): MemeTemplate[] {
  const q = query.trim().toLowerCase();
  return TEMPLATES.filter((t) => {
    if (category && t.category !== category) return false;
    if (!q) return true;
    return (
      t.name.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.keywords.some((k) => k.includes(q))
    );
  });
}

// Render a tiny thumbnail SVG data URL for a template (used in card previews)
export function templateThumbnail(t: MemeTemplate, size = 240): string {
  const scale = size / Math.max(t.width, t.height);
  const w = t.width * scale;
  const h = t.height * scale;
  let bg = "";
  if (t.background.type === "gradient") {
    bg = `<defs><linearGradient id="g_${t.id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${t.background.gradientFrom}"/><stop offset="1" stop-color="${t.background.gradientTo}"/></linearGradient></defs><rect width="${t.width}" height="${t.height}" fill="url(#g_${t.id})"/>`;
  } else if (t.background.type === "transparent") {
    bg = `<rect width="${t.width}" height="${t.height}" fill="#ffffff"/>`;
  } else {
    bg = `<rect width="${t.width}" height="${t.height}" fill="${t.background.color}"/>`;
  }
  let layers = "";
  for (const layer of t.layers) {
    if (layer.type === "shape") {
      if (layer.shape === "rectangle" || layer.shape === "panel") {
        layers += `<rect x="${layer.x}" y="${layer.y}" width="${layer.width}" height="${layer.height}" fill="${layer.fill}" stroke="${layer.stroke}" stroke-width="${layer.strokeWidth}"/>`;
      } else if (layer.shape === "ellipse") {
        layers += `<ellipse cx="${layer.x + layer.width / 2}" cy="${layer.y + layer.height / 2}" rx="${layer.width / 2}" ry="${layer.height / 2}" fill="${layer.fill}" stroke="${layer.stroke}" stroke-width="${layer.strokeWidth}"/>`;
      }
    } else if (layer.type === "text") {
      const display = layer.uppercase ? layer.text.toUpperCase() : layer.text;
      layers += `<text x="${layer.x + layer.width / 2}" y="${layer.y + layer.fontSize}" width="${layer.width}" text-anchor="middle" font-family="${layer.fontFamily.replace(/"/g, "'")}" font-size="${layer.fontSize}" font-weight="${layer.fontWeight}" fill="${layer.color}" stroke="${layer.outlineColor}" stroke-width="${layer.outlineWidth / 4}">${escapeSvg(display)}</text>`;
    }
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${t.width} ${t.height}" width="${w}" height="${h}">${bg}${layers}</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

function escapeSvg(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
